#!/bin/bash
# Script to delete lowercase secrets and recreate with UPPERCASE names

echo "Step 1: Deleting old lowercase secrets..."
aws ssm delete-parameter --name "/copilot/property-intel/production/secrets/attom-api-key" 2>/dev/null && echo "✓ Deleted attom-api-key" || echo "✗ attom-api-key not found"
aws ssm delete-parameter --name "/copilot/property-intel/production/secrets/openai-api-key" 2>/dev/null && echo "✓ Deleted openai-api-key" || echo "✗ openai-api-key not found"
aws ssm delete-parameter --name "/copilot/property-intel/production/secrets/secret-key" 2>/dev/null && echo "✓ Deleted secret-key" || echo "✗ secret-key not found"
aws ssm delete-parameter --name "/copilot/property-intel/production/secrets/clerk-secret-key" 2>/dev/null && echo "✓ Deleted clerk-secret-key" || echo "✗ clerk-secret-key not found"
aws ssm delete-parameter --name "/copilot/property-intel/production/secrets/smarty-auth-id" 2>/dev/null && echo "✓ Deleted smarty-auth-id" || echo "✗ smarty-auth-id not found"
aws ssm delete-parameter --name "/copilot/property-intel/production/secrets/smarty-auth-token" 2>/dev/null && echo "✓ Deleted smarty-auth-token" || echo "✗ smarty-auth-token not found"
aws ssm delete-parameter --name "/copilot/property-intel/production/secrets/hud-api-key" 2>/dev/null && echo "✓ Deleted hud-api-key" || echo "✗ hud-api-key not found"
aws ssm delete-parameter --name "/copilot/property-intel/production/secrets/google-maps-api-key" 2>/dev/null && echo "✓ Deleted google-maps-api-key" || echo "✗ google-maps-api-key not found"

echo ""
echo "Step 2: Now run these commands to create UPPERCASE secrets:"
echo ""
echo "copilot secret init --name ATTOM_API_KEY"
echo "copilot secret init --name OPENAI_API_KEY"
echo "copilot secret init --name SECRET_KEY"
echo "copilot secret init --name CLERK_SECRET_KEY"
echo "copilot secret init --name SMARTY_AUTH_ID"
echo "copilot secret init --name SMARTY_AUTH_TOKEN"
echo "copilot secret init --name HUD_API_KEY"
echo "copilot secret init --name GOOGLE_MAPS_API_KEY"
echo ""
echo "Paste the values from .env.production.local when prompted"
